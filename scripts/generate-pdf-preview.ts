// The files of pdf.js the preview browser loads to draw a PDF page: the
// library, its parser, the standard fonts and character maps PDFs name
// without embedding, the image decoders and one color profile. Each is
// embedded in the server as a file and served to the preview page alone,
// so a preview job never reaches the network for them.
import { readdirSync, readFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = new URL("../", import.meta.url)
const packageRoot = dirname(
  fileURLToPath(import.meta.resolve("pdfjs-dist/package.json"))
)
const { version } = JSON.parse(
  readFileSync(join(packageRoot, "package.json"), "utf8")
) as { version: string }

const TYPES: Record<string, string> = {
  mjs: "text/javascript",
  wasm: "application/wasm",
  bcmap: "application/octet-stream",
  pfb: "application/octet-stream",
  ttf: "font/ttf",
  icc: "application/vnd.iccprofile",
}

/** Each served path with the package file behind it. */
const files: Array<[served: string, source: string]> = [
  ["pdf.mjs", "build/pdf.min.mjs"],
  ["pdf.worker.mjs", "build/pdf.worker.min.mjs"],
]
for (const [folder, extensions] of [
  ["standard_fonts", ["pfb", "ttf"]],
  ["cmaps", ["bcmap"]],
  ["wasm", ["wasm"]],
  ["iccs", ["icc"]],
] as const) {
  for (const name of readdirSync(join(packageRoot, folder)).sort()) {
    // quickjs-eval runs scripts a PDF carries, which a preview never does.
    if (name.startsWith("quickjs")) continue
    if (extensions.some((extension) => name.endsWith(`.${extension}`)))
      files.push([`${folder}/${name}`, `${folder}/${name}`])
  }
}

const imports = files.map(
  ([, source], index) =>
    `import file${index} from "pdfjs-dist/${source}" with { type: "file" }`
)
const entries = files.map(([served, source], index) => {
  const type = TYPES[source.slice(source.lastIndexOf(".") + 1)]
  if (!type) throw new Error(`No media type for ${source}`)
  return `  ${JSON.stringify(`/pdfjs/${served}`)}: { url: file${index}, type: ${JSON.stringify(type)} },`
})
const text = `// Generated by scripts/generate-pdf-preview.ts. Do not edit.
${imports.join("\n")}

/** The pdf.js release these files are from; part of every PDF picture's identity. */
export const PDF_RENDERER_VERSION = ${JSON.stringify(`pdfjs-dist-${version}`)}

/** What the PDF preview page may load, by the path it asks for. */
export const PDF_PREVIEW_ASSETS: Readonly<
  Record<string, { url: string; type: string }>
> = {
${entries.join("\n")}
}
`
const destination = new URL(
  "packages/server/src/generated/pdf-preview-assets.ts",
  root
)
if (process.argv.includes("--check")) {
  const current = await Bun.file(destination)
    .text()
    .catch(() => "")
  if (current !== text)
    throw new Error(
      "PDF preview assets are stale; run bun scripts/generate-pdf-preview.ts"
    )
} else await Bun.write(destination, text)
