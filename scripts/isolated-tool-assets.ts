import { fileURLToPath } from "node:url"
import { createHash } from "node:crypto"
import { gzipSync } from "node:zlib"

const root = new URL("../", import.meta.url)

/** Also used by release assembly to account for embedded browser/VM licenses. */
export async function buildIsolatedToolAssets() {
  const worker = await Bun.build({
    entrypoints: [
      fileURLToPath(new URL("packages/ui/src/tool-runtime/worker.ts", root)),
    ],
    target: "browser",
    format: "iife",
    define: { "import.meta.url": "globalThis.location.href" },
    minify: true,
    metafile: true,
  })
  if (!worker.success)
    throw new AggregateError(worker.logs, "Tool worker build failed")
  const frame = await Bun.build({
    entrypoints: [
      fileURLToPath(new URL("packages/ui/src/tool-runtime/frame.ts", root)),
    ],
    target: "browser",
    format: "iife",
    define: {
      __WORKTABLE_TOOL_WORKER_SOURCE__: JSON.stringify(
        await worker.outputs[0]!.text()
      ),
    },
    minify: true,
    metafile: true,
  })
  if (!frame.success)
    throw new AggregateError(frame.logs, "Tool frame build failed")
  const source =
    "// Generated by scripts/generate-isolated-tool.ts. Do not edit.\n" +
    (await frame.outputs[0]!.text())
  const hash = createHash("sha256").update(source).digest("hex")
  return {
    source,
    gzip: gzipSync(source, { level: 9 }),
    manifest: {
      profile: "isolated-v1",
      hash,
      path: `/worktable-runtime/${hash}/tool.js`,
    },
    metafiles: [worker.metafile!, frame.metafile!],
  }
}
