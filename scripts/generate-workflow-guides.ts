// The server serves the full guide behind each bundled Worktable skill through
// worktable_guidance (topic "workflow"). The SKILL.md that apps install only
// points there, so a copy an app froze at install still follows the current
// guide. This embeds each guide in a generated module the server ships.
import { readdir, readFile, writeFile } from "node:fs/promises"
import { join } from "node:path"
import {
  skillSourcePath,
  WORKFLOW_GUIDE_DIRECTORY,
  workflowGuidePath,
  WORKTABLE_BUNDLED_SKILLS,
} from "./skill-inventory"

const check = process.argv.slice(2).includes("--check")
const repositoryRoot = join(import.meta.dir, "..")
const destination = join(
  repositoryRoot,
  "packages/server/src/mcp/workflow-guides.generated.ts"
)

const files = new Set(
  (await readdir(join(repositoryRoot, WORKFLOW_GUIDE_DIRECTORY))).filter(
    (file) => file.endsWith(".md")
  )
)
const guides: Record<string, string> = {}
for (const skill of WORKTABLE_BUNDLED_SKILLS) {
  const skillFile = await readFile(
    skillSourcePath(repositoryRoot, skill, "SKILL.md"),
    "utf8"
  )
  const points = skillFile.includes(`name: "${skill.name}"`)
  const hasGuide = files.delete(`${skill.name}.md`)
  if (points !== hasGuide) {
    throw new Error(
      hasGuide
        ? `${skill.name}'s SKILL.md must point to its guide with worktable_guidance`
        : `${skill.name}'s SKILL.md points to a guide missing from ${WORKFLOW_GUIDE_DIRECTORY}`
    )
  }
  if (!hasGuide) continue
  guides[skill.name] = (
    await readFile(workflowGuidePath(repositoryRoot, skill.name), "utf8")
  ).trim()
}
if (files.size > 0) {
  throw new Error(
    `Guides with no bundled skill: ${[...files].sort().join(", ")}`
  )
}

const contents = `// Generated by scripts/generate-workflow-guides.ts from the guides in
// ${WORKFLOW_GUIDE_DIRECTORY}.
// Run 'bun run generate:guides' after changing one.

export const WORKFLOW_GUIDES = ${JSON.stringify(guides, null, 2)} as const

export type WorkflowGuideName = keyof typeof WORKFLOW_GUIDES

export const WORKFLOW_GUIDE_NAMES = Object.keys(WORKFLOW_GUIDES) as [
  WorkflowGuideName,
  ...WorkflowGuideName[],
]
`

if (check) {
  const actual = await readFile(destination, "utf8").catch(() => "")
  if (actual !== contents) {
    throw new Error(
      "Workflow guides are stale. Run 'bun run generate:guides' and commit the result."
    )
  }
  console.log(`Verified ${Object.keys(guides).length} workflow guides`)
} else {
  await writeFile(destination, contents)
  console.log(`Wrote ${Object.keys(guides).length} workflow guides`)
}
