// Writes the icon library HTML Docs name with <svg data-icon="...">
// (packages/server/src/html-icons.ts): every Lucide icon's drawing, the old
// names Lucide still answers to, and its search tags, from lucide-static at
// the version the app's lucide-react uses, so a page draws what the app draws.

import { existsSync, readFileSync } from "node:fs"
import { join } from "node:path"

const root = join(import.meta.dir, "..")
const output = "packages/server/src/html-icons.generated.json"
const lucideStatic = join(root, "node_modules/lucide-static")

type IconNode = Array<[string, Record<string, string | number>]>

function packageVersion(dir: string): string {
  return JSON.parse(readFileSync(join(dir, "package.json"), "utf8")).version
}

const version = packageVersion(lucideStatic)
const appVersion = packageVersion(join(root, "node_modules/lucide-react"))
if (version !== appVersion) {
  throw new Error(
    `lucide-static ${version} must match the app's lucide-react ${appVersion}`
  )
}

/** The key a name is looked up by: case, dashes and underscores ignored. */
function iconKey(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]/g, "")
}

function attribute(value: string | number): string {
  return String(value).replace(/&/g, "&amp;").replace(/"/g, "&quot;")
}

const nodes: Record<string, IconNode> = JSON.parse(
  readFileSync(join(lucideStatic, "icon-nodes.json"), "utf8")
)
const allTags: Record<string, string[]> = JSON.parse(
  readFileSync(join(lucideStatic, "tags.json"), "utf8")
)

const icons: Record<string, string> = {}
const keys = new Map<string, string>()
for (const name of Object.keys(nodes).sort()) {
  const key = iconKey(name)
  const taken = keys.get(key)
  if (taken) throw new Error(`${name} and ${taken} share the key ${key}`)
  keys.set(key, name)
  icons[name] = nodes[name]!.map(([tag, attrs]) => {
    const text = Object.entries(attrs)
      .filter(([name]) => name !== "key")
      .map(([name, value]) => `${name}="${attribute(value)}"`)
      .join(" ")
    return `<${tag} ${text}/>`
  }).join("")
}

// Lucide's module exports each icon under its current and former names.
const aliases: Record<string, string> = {}
const exports = readFileSync(
  join(lucideStatic, "dist/esm/lucide-static.js"),
  "utf8"
)
for (const line of exports.matchAll(
  /export \{([^}]+)\} from '\.\/icons\/([a-z0-9-]+)\.js'/g
)) {
  const name = line[2]!
  if (!icons[name]) continue
  for (const exported of line[1]!.matchAll(/default as (\w+)/g)) {
    const key = iconKey(exported[1]!)
    if (key === iconKey(name)) continue
    const taken = keys.get(key)
    if (taken && taken !== name) continue
    aliases[key] = name
  }
}

const tags: Record<string, string[]> = {}
for (const name of Object.keys(icons)) {
  if (allTags[name]?.length) tags[name] = allTags[name]!
}

const licenseOutput = "packages/server/src/html-icons-LICENSE.txt"
const license = readFileSync(join(lucideStatic, "LICENSE"), "utf8").trimEnd()

const outputs: Array<[string, string]> = [
  [
    output,
    `${JSON.stringify({
      note: "Generated by scripts/generate-html-icons.ts. Do not edit by hand.",
      source: `lucide-static@${version}`,
      license: "ISC, in html-icons-LICENSE.txt",
      icons,
      aliases: Object.fromEntries(Object.entries(aliases).sort()),
      tags,
    })}\n`,
  ],
  // Lucide's license travels with the copy of its icons, as its terms ask.
  [
    licenseOutput,
    `The icons in html-icons.generated.json are Lucide's (lucide-static@${version}, https://lucide.dev), under this license:\n\n${license}\n`,
  ],
]

if (import.meta.main) {
  let drifted = false
  for (const [relativePath, content] of outputs) {
    const path = join(root, relativePath)
    if (process.argv.includes("--check")) {
      if (!existsSync(path) || readFileSync(path, "utf8") !== content) {
        console.error(
          `${relativePath} is out of date. Run bun run generate:icons.`
        )
        drifted = true
      }
    } else {
      await Bun.write(path, content)
      console.log(`Wrote ${relativePath}`)
    }
  }
  if (drifted) process.exit(1)
}
