// The server serves the current text of each bundled Worktable skill through
// worktable_guidance (topic "workflow"), so a copy an app froze at install can
// point there and still follow the current guide. This embeds each skill's
// body, without its frontmatter, in a generated module the server ships.
import { readFile, writeFile } from "node:fs/promises"
import { join } from "node:path"
import { skillSourcePath, WORKTABLE_BUNDLED_SKILLS } from "./skill-inventory"

const check = process.argv.slice(2).includes("--check")
const repositoryRoot = join(import.meta.dir, "..")
const destination = join(
  repositoryRoot,
  "packages/server/src/mcp/workflow-guides.generated.ts"
)

function body(source: string): string {
  if (!source.startsWith("---\n")) return source.trim()
  const end = source.indexOf("\n---", 4)
  if (end < 0) throw new Error("A skill's frontmatter isn't closed")
  return source.slice(source.indexOf("\n", end + 1) + 1).trim()
}

const guides: Record<string, string> = {}
for (const skill of WORKTABLE_BUNDLED_SKILLS) {
  guides[skill.name] = body(
    await readFile(skillSourcePath(repositoryRoot, skill, "SKILL.md"), "utf8")
  )
}

const contents = `// Generated by scripts/generate-workflow-guides.ts from the bundled skills in
// plugins/worktable/skills. Run 'bun run generate:guides' after changing one.

export const WORKFLOW_GUIDES = ${JSON.stringify(guides, null, 2)} as const

export type WorkflowGuideName = keyof typeof WORKFLOW_GUIDES

export const WORKFLOW_GUIDE_NAMES = Object.keys(WORKFLOW_GUIDES) as [
  WorkflowGuideName,
  ...WorkflowGuideName[],
]
`

if (check) {
  const actual = await readFile(destination, "utf8").catch(() => "")
  if (actual !== contents) {
    throw new Error(
      "Workflow guides are stale. Run 'bun run generate:guides' and commit the result."
    )
  }
  console.log(`Verified ${Object.keys(guides).length} workflow guides`)
} else {
  await writeFile(destination, contents)
  console.log(`Wrote ${Object.keys(guides).length} workflow guides`)
}
